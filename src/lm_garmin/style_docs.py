"""Document the translation rules and the effective TYP styles."""

from .products import PRODUCTS, STYLES_DIR
from .stylegen import Rule, load, typ_rules

TRANSLATION_TABLE = STYLES_DIR.parent / "docs" / "translation-table.md"

INTRO = """<!-- Generated by `lm-garmin style generate`. Edit the style mappings to update it. -->

# Lantmäteriet and OSM to Garmin translation table

The tables follow rule order in each product's `mapping.csv`. Any means the rule
applies regardless of `objekttypnr`. Resolution values are mkgmap resolutions.
Only resolutions configured for the product are listed. Overlapping rules are
evaluated in order. `continue` allows another matching rule to run.

TYP appearance uses the first definition for each geometry and Garmin type,
including when later rules reuse that type. Garmin default means the build emits
no custom point icon for the type. Widths and icon sizes are in pixels.

The base table shows each rule's configured levels. In a build with
[official overview sources](overview-sources.md), the `mark100` and `sankmark100`
rows replace Topografi 50 surface polygons at resolution 20, and `mark250` and
`sankmark250` replace them at resolution 18. These suffixed layers are internal
build tags. See the [Topografi 50 inventory](data-inventory.md) for source layers
and object types.

## Cartographic decisions

- `byggnadspunkt` buildings use unrotated squares in the three size classes.
  The source rotation is retained in the delivery and Garmin has no per-point
  rotation for these TYP icons.
  [Design notes](PLAN.md#54-things-garmin-cannot-do-accepted-deviations)
- `markkantlinje` draws shorelines and glacier boundaries at detailed levels.
  Polygon fills convey the other land-cover boundaries. The omitted boundary
  codes and reasons appear in the table.
- `hojdkurvstext` is explicitly dropped. Index contours derive elevation labels
  from `ele`. The build encodes elevation in feet so a Garmin set to metric
  displays metres, as verified in the [device tests](device-testing.md).
"""


def _code(text: str) -> str:
    return "`" + text.replace("|", r"\|") + "`" if text else "—"


def _appearance(rule: Rule) -> str:
    if rule.kind == "point" and rule.pattern == "none":
        return "Garmin default"
    colours = "/".join(filter(None, (rule.colour, rule.colour2)))
    parts = [rule.pattern or "solid"]
    if colours:
        parts.append(f"`{colours}`")
    if rule.kind == "polygon":
        parts.append(f"order {rule.order or 1}")
    elif rule.kind == "point":
        size = max(int(rule.width or 5), 1)
        parts.append(f"{size}×{size} px")
    else:
        width = 1 if rule.pattern == "label" else max(int(rule.width or 1), 1)
        parts.append(f"{width} px")
    return ", ".join(parts)


def render_translation_table() -> str:
    lines = [INTRO.rstrip()]
    for product in PRODUCTS.values():
        rules = load(product.style_dir / "mapping.csv")
        typ = typ_rules(rules)
        resolutions = [int(level.split(":")[1]) for level in product.levels.split(",")]
        lines.extend(
            [
                "",
                f"## {product.name}",
                "",
                f"[Style mapping](../styles/{product.style}/mapping.csv) · "
                f"[TYP source](../styles/{product.style}/typ/{product.style}.txt)",
                "",
                "| Layer | Object type | Description | Condition | Geometry | Garmin type "
                "| Resolutions | TYP appearance | Label and options |",
                "|---|---|---|---|---|---|---|---|---|",
            ]
        )
        for rule in rules:
            encoded, appearance = "—", "—"
            if rule.kind != "drop":
                low, _, high = rule.resolution.partition("-")
                encoded = ", ".join(
                    str(res) for res in resolutions if int(low) <= res <= int(high or "24")
                )
                appearance = _appearance(typ[rule.kind, rule.type])
            cells = (
                _code(rule.layer),
                _code(rule.t) if rule.t else "Any",
                rule.description.replace("|", r"\|"),
                _code(rule.condition),
                rule.kind,
                _code(rule.type),
                encoded or "—",
                appearance,
                ", ".join(_code(value) for value in (rule.name, rule.options) if value) or "—",
            )
            lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"
